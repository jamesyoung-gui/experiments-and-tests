// OWNER: eggs. Build-time step: TrueType outlines -> SVG path data for every character the easter eggs print.
// usage: node src/fx/egg-glyphs.gen.mjs   (writes src/fx/egg-glyphs.js; no runtime fonts)
// Latin display: DejaVu Sans Bold. HUD lines: DejaVu Sans Mono Bold (Bitstream Vera licence).
// CJK: WenQuanYi Zen Hei (GPL + font embedding exception) — every CJK character found in eggs.js is packed
// automatically, so a new caption never ships with a missing glyph.
// Units: em = 1000, y down, baseline at y = 0.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadFont } from '../../tools/ttf.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const LAT_CHARS = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!?.,'·-:&()—/#_+%>×~^@*=[];";
const src0 = fs.readFileSync(path.join(here, 'eggs.js'), 'utf8');
const cjk = new Set();
for (const ch of src0) if (/[　-〿㐀-鿿＀-￯゠-ヿ]/.test(ch)) cjk.add(ch);
const ZH_CHARS = [...cjk].sort().join('');
function pack(file, chars) {
  const font = loadFont(file), out = {};
  for (const ch of chars) {
    if (out[ch]) continue;
    const g = font.gid(ch.codePointAt(0));
    if (!g && ch !== ' ') throw new Error(`missing glyph ${ch} in ${path.basename(file)}`);
    const { d } = ch === ' ' ? { d: '' } : font.text(ch, { size: 1000 });
    out[ch] = [Math.round(font.adv(g) * 1000 / font.upem), d.replace(/-?\d+(\.\d+)?/g, m => String(Math.round(+m))).replace(/ -/g, '-')];
  }
  return out;
}
const lat = pack('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf', LAT_CHARS);
const mono = pack('/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf', LAT_CHARS);
const zh = pack('/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc', ZH_CHARS);
const src = `// GENERATED by egg-glyphs.gen.mjs — do not edit. Glyph outlines (em 1000, y down, baseline 0). Each entry: [advance, d].
// Latin: DejaVu Sans Bold + DejaVu Sans Mono Bold (Bitstream Vera / DejaVu licence). CJK: WenQuanYi Zen Hei (GPL v2 + font embedding exception).
export const LAT = ${JSON.stringify(lat)};
export const MONO = ${JSON.stringify(mono)};
export const ZH = ${JSON.stringify(zh)};
`;
fs.writeFileSync(path.join(here, 'egg-glyphs.js'), src);
console.log('egg-glyphs.js', (src.length / 1024).toFixed(1) + ' KB', ZH_CHARS.length, 'CJK');
