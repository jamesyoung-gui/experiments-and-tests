// OWNER: print. Build-time step: TrueType outlines -> SVG path data for every character the HUD frame prints.
// usage: node src/world/print-glyphs.gen.mjs   (writes src/world/print-glyphs.js; commit the output, no runtime fonts)
// The character sets are derived from the strings print.js actually prints (collectText() runs its build() with a
// stub context and records every character per face), plus a base set per face, so the file carries no unused
// glyphs. print.js reads the faces through a namespace import, so this script can import it while a face is missing.
// Faces (all outlines may be embedded):
//   LAT  DejaVu Sans Bold       the NEON PELICAN title + the UI's wordmark / odometer digits (kept for ui.js)
//   SANS DejaVu Sans            the mission caption
//   MONO DejaVu Sans Mono Bold  every HUD readout (tabular digits)
//   ZH   WenQuanYi Zen Hei      CJK + katakana (GPL v2 + font embedding exception)
// Units: em = 1000, y down, baseline at y = 0, pen origin at x = 0. Each entry: [advance, d].
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadFont } from '../../tools/ttf.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const DJ = '/usr/share/fonts/truetype/dejavu/';
const FONTS = {
  LAT: DJ + 'DejaVuSans-Bold.ttf',
  SANS: DJ + 'DejaVuSans.ttf',
  MONO: DJ + 'DejaVuSansMono-Bold.ttf',
  ZH: '/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc',
};
// base sets: ui.js prints PELICAN BAY + digits with LAT; the HUD digit slots need 0-9 in MONO
const BASE = {
  LAT: 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789·.,-/:&\'#%@$',
  SANS: '0123456789',
  MONO: 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789·.,-/:%#+×°¥()!?',
  ZH: '鹈鹕湾',
};
const { collectText } = await import('./print.js');
const used = collectText();
const sets = Object.fromEntries(Object.entries(BASE).map(([k, s]) => [k, new Set([...s, ...(used[k] || '')])]));

function pack(file, chars) {
  const font = loadFont(file);
  const out = {};
  for (const ch of [...chars].sort()) {
    const g = font.gid(ch.codePointAt(0));
    if (!g) throw new Error(`missing glyph ${ch} (U+${ch.codePointAt(0).toString(16)}) in ${path.basename(file)}`);
    const { d } = font.text(ch, { size: 1000 });
    // round to integers in the 1000-unit em: < 0.1 px error at any size used on the HUD
    const dd = d.replace(/-?\d+(\.\d+)?/g, m => String(Math.round(+m))).replace(/ -/g, '-');
    out[ch] = [Math.round(font.adv(g) * 1000 / font.upem), dd];
  }
  return out;
}
let src = `// GENERATED by print-glyphs.gen.mjs — do not edit. Glyph outlines as SVG path data (em 1000, y down, baseline 0).
// LAT: DejaVu Sans Bold · SANS: DejaVu Sans · MONO: DejaVu Sans Mono Bold (Bitstream Vera / DejaVu licence).
// ZH: WenQuanYi Zen Hei (GPL v2 + font embedding exception). Each entry: [advance, d].
`;
for (const [k, file] of Object.entries(FONTS)) src += `export const ${k} = ${JSON.stringify(pack(file, sets[k]))};\n`;
fs.writeFileSync(path.join(here, 'print-glyphs.js'), src);
console.log('print-glyphs.js', (src.length / 1024).toFixed(1) + ' KB', Object.entries(sets).map(([k, s]) => `${k} ${s.size}`).join(' · '));
