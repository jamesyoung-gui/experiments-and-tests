// OWNER: director. Build-time step: TrueType outlines -> SVG path data for the director's signs and pop words.
// usage: node src/world/director-glyphs.gen.mjs   (writes src/world/director-glyphs.js; no runtime fonts)
// Latin: DejaVu Sans Bold (Bitstream Vera licence). CJK: WenQuanYi Zen Hei (GPL + font embedding exception).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadFont } from '../../tools/ttf.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const LAT_CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!?.,'-:&";
const ZH_CHARS = '下坡冲刺风筝节你好喵嘎哗啦雾灯塔前方有雨慢行啊呀守人烟花';
function pack(file, chars) {
  const font = loadFont(file), out = {};
  for (const ch of chars) {
    if (out[ch]) continue;
    const g = font.gid(ch.codePointAt(0));
    if (!g) throw new Error(`missing glyph ${ch}`);
    const { d } = font.text(ch, { size: 1000 });
    out[ch] = [Math.round(font.adv(g) * 1000 / font.upem), d.replace(/-?\d+(\.\d+)?/g, m => String(Math.round(+m))).replace(/ -/g, '-')];
  }
  return out;
}
const lat = pack('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf', LAT_CHARS);
const zh = pack('/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc', ZH_CHARS);
const src = `// GENERATED by director-glyphs.gen.mjs — do not edit. Glyph outlines (em 1000, y down, baseline 0). [advance, d].
// Latin: DejaVu Sans Bold (Bitstream Vera / DejaVu licence). CJK: WenQuanYi Zen Hei (GPL v2 + font embedding exception).
export const GLYPHS = ${JSON.stringify({ ...lat, ...zh })};
`;
fs.writeFileSync(path.join(here, 'director-glyphs.js'), src);
console.log('director-glyphs.js', (src.length / 1024).toFixed(1) + ' KB');
