// OWNER: eggs. Build-time step: TrueType outlines -> SVG path data for every character the easter eggs print.
// usage: node src/fx/egg-glyphs.gen.mjs   (writes src/fx/egg-glyphs.js; no runtime fonts)
// Latin: DejaVu Sans Bold (Bitstream Vera licence). CJK: WenQuanYi Zen Hei (GPL + font embedding exception).
// Units: em = 1000, y down, baseline at y = 0.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadFont } from '../../drafts/C-poster/ttf.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const LAT_CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!?.,'·-:&()—";
const ZH_CHARS = '褐鹈鹕繁殖羽链条接错啦喵公里别慌哗许愿嘎哔来湾一起骑车吧有鱼同享，！·见字如面致海边的朋友你好？';
function pack(file, chars) {
  const font = loadFont(file), out = {};
  for (const ch of chars) {
    if (out[ch]) continue;
    const g = font.gid(ch.codePointAt(0));
    if (!g) throw new Error(`missing glyph ${ch} in ${path.basename(file)}`);
    const { d } = font.text(ch, { size: 1000 });
    out[ch] = [Math.round(font.adv(g) * 1000 / font.upem), d.replace(/-?\d+(\.\d+)?/g, m => String(Math.round(+m))).replace(/ -/g, '-')];
  }
  return out;
}
const lat = pack('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf', LAT_CHARS);
const zh = pack('/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc', ZH_CHARS);
const src = `// GENERATED by egg-glyphs.gen.mjs — do not edit. Glyph outlines (em 1000, y down, baseline 0). Each entry: [advance, d].
// Latin: DejaVu Sans Bold (Bitstream Vera / DejaVu licence). CJK: WenQuanYi Zen Hei (GPL v2 + font embedding exception).
export const LAT = ${JSON.stringify(lat)};
export const ZH = ${JSON.stringify(zh)};
`;
fs.writeFileSync(path.join(here, 'egg-glyphs.js'), src);
console.log('egg-glyphs.js', (src.length / 1024).toFixed(1) + ' KB');
