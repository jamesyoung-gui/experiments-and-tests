// OWNER: print. Build-time step: TrueType outlines -> SVG path data for every character the poster furniture prints.
// usage: node src/world/print-glyphs.gen.mjs   (writes src/world/print-glyphs.js; commit the output, no runtime fonts)
// Latin: DejaVu Sans Bold (Bitstream Vera licence, outlines may be embedded). CJK: WenQuanYi Zen Hei (GPL + font
// exception, outlines may be embedded). Units: em = 1000, y down, baseline at y = 0, pen origin at x = 0.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadFont } from '../../tools/ttf.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const LAT = '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf';
const ZH = '/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc';
const LAT_CHARS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789·.,-/:&\'№°→';
const ZH_CHARS = '鹈鹕湾印制邮政分单程灯塔角海滨路';

function pack(file, chars) {
  const font = loadFont(file);
  const out = {};
  for (const ch of chars) {
    const g = font.gid(ch.codePointAt(0));
    if (!g) throw new Error(`missing glyph ${ch} in ${path.basename(file)}`);
    const { d } = font.text(ch, { size: 1000 });
    // round to integers in the 1000-unit em: < 0.1 px error at any size used on the poster
    const dd = d.replace(/-?\d+(\.\d+)?/g, m => String(Math.round(+m))).replace(/ -/g, '-');
    out[ch] = [Math.round(font.adv(g) * 1000 / font.upem), dd];
  }
  return out;
}
const lat = pack(LAT, LAT_CHARS);
const zh = pack(ZH, ZH_CHARS);
const src = `// GENERATED by print-glyphs.gen.mjs — do not edit. Glyph outlines as SVG path data (em 1000, y down, baseline 0).
// Latin: DejaVu Sans Bold (Bitstream Vera / DejaVu licence). CJK: WenQuanYi Zen Hei (GPL v2 + font embedding exception).
// Each entry: [advance, d].
export const LAT = ${JSON.stringify(lat)};
export const ZH = ${JSON.stringify(zh)};
`;
fs.writeFileSync(path.join(here, 'print-glyphs.js'), src);
console.log('print-glyphs.js', (src.length / 1024).toFixed(1) + ' KB', Object.keys(lat).length + Object.keys(zh).length, 'glyphs');
