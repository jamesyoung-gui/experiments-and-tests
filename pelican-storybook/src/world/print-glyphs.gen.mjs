// OWNER: print. Build-time step: TrueType outlines -> SVG path data for every character the picture-book page prints.
// usage: node src/world/print-glyphs.gen.mjs   (writes src/world/print-glyphs.js; commit the output, no runtime fonts)
// STYLE-B §4: Latin = DejaVu Serif (Bold for the hand-lettered title, the chapter plate, page numbers; Book for the story
// captions and running heads; Bitstream Vera / DejaVu licence, outlines may be embedded). CJK = WenQuanYi Zen Hei
// (GPL v2 + font embedding exception). Units: em = 1000, y down, baseline at y = 0, pen origin at x = 0.
// The CJK set is harvested from print.js itself (every Han character in its source), so a new caption can never miss
// a glyph: edit the text, rerun this script.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadFont } from '../../tools/ttf.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const FONTS = '/usr/share/fonts/truetype';
const SERB = `${FONTS}/dejavu/DejaVuSerif-Bold.ttf`;
const SER = `${FONTS}/dejavu/DejaVuSerif.ttf`;
const ZHF = `${FONTS}/wqy/wqy-zenhei.ttc`;

const ASCII = Array.from({ length: 94 }, (_, i) => String.fromCharCode(33 + i)).join('');
const EXTRA = '·—’“”→№…';
// Han characters + CJK punctuation used anywhere in print.js (captions, headers, numerals) + what ui.js borrows
const src = fs.readFileSync(path.join(here, 'print.js'), 'utf8');
const han = new Set((src.match(/[　-〿一-鿿＀-￯]/g) || []));
for (const ch of '鹈鹕湾零一二三四五六七八九十') han.add(ch);
const ZH_CHARS = [...han].sort().join('');

function pack(file, chars) {
  const font = loadFont(file);
  const out = {};
  for (const ch of chars) {
    const g = font.gid(ch.codePointAt(0));
    if (!g) { console.warn(`  (no glyph ${ch} in ${path.basename(file)})`); continue; }
    const { d } = font.text(ch, { size: 1000 });
    // integers in the 1000-unit em: < 0.1 px error at every size used on the page
    const dd = d.replace(/-?\d+(\.\d+)?/g, m => String(Math.round(+m))).replace(/ -/g, '-');
    out[ch] = [Math.round(font.adv(g) * 1000 / font.upem), dd];
  }
  return out;
}
const lat = pack(SERB, ASCII + EXTRA);
const ser = pack(SER, ASCII + EXTRA);
const zh = pack(ZHF, ZH_CHARS);
const out = `// GENERATED by print-glyphs.gen.mjs — do not edit. Glyph outlines as SVG path data (em 1000, y down, baseline 0).
// LAT: DejaVu Serif Bold · SER: DejaVu Serif (Bitstream Vera / DejaVu licence). ZH: WenQuanYi Zen Hei (GPL v2 + font
// embedding exception). Each entry: [advance, d].
export const LAT = ${JSON.stringify(lat)};
export const SER = ${JSON.stringify(ser)};
export const ZH = ${JSON.stringify(zh)};
`;
fs.writeFileSync(path.join(here, 'print-glyphs.js'), out);
console.log('print-glyphs.js', (out.length / 1024).toFixed(1) + ' KB', Object.keys(lat).length + Object.keys(ser).length + Object.keys(zh).length, 'glyphs,', ZH_CHARS.length, 'CJK');
